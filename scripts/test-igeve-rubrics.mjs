import assert from 'node:assert/strict';
import { rubricKey, rubricOperationKind, rubricBalance, rubricMonthInvoices, rubricScopeInvoices, reductionSuggestion, withDeferredItems, complementSuggestion, createRubricInvoice, shiftRubricMonth } from '../src/lib/igeveRubrics.ts';
import { invoiceTotal, createLocationBillingInvoice, locationTotals, billingOperationPriceKey, billingInvoiceCategoryMatches, validateInvoice } from '../src/lib/igeveBilling.ts';
const operations = [
  { id: 'b', name: 'Operação Boituva', city: 'Boituva' },
  { id: 'm', name: 'Operação Maceió', city: 'Maceió' },
  { id: 'g', name: 'Operação Gauianases', city: 'Gauianases' },
];
assert.equal(rubricOperationKind(operations[0]), 'operation');
assert.equal(rubricOperationKind(operations[1]), 'local');
assert.equal(rubricOperationKind(operations[2]), 'operation');
assert.equal(rubricOperationKind({ id: 'x', name: 'Outra operação', city: '' }), null);
assert.equal(shiftRubricMonth('2026-12', 1), '2027-01');
assert.equal(shiftRubricMonth('2026-01', -1), '2025-12');
const points = [{ id: 'p1', name: 'Escola A', operationId: 'm' }, { id: 'p2', name: 'Escola B', operationId: 'm' }];
const orders = [{ id: 'order', operationId: 'm', category: 'Estocáveis', deliveryDate: '2026-11', importedAt: '2026-11-01T12:00:00Z', deliveries: points.map((point, i) => ({ id: `d${i}`, deliveryPointId: point.id, items: [{ product: 'Arroz', unit: 'KG', quantity: 10 }] })) }];
const prices = { [billingOperationPriceKey('m', 'Estocáveis', 'Arroz', 'KG')]: { salePrice: 10 } };
const rubric = { key: rubricKey('m', 'p1', '2026-11'), operationId: 'm', pointId: 'p1', month: '2026-11', amount: 90, previousAdjustment: 0, adjustmentNotes: '' };
const original = rubricMonthInvoices(orders, operations, points, prices, [], '2026-11');
assert.equal(original.length, 2);
const scope = rubricScopeInvoices(original, rubric, orders, points);
assert.equal(scope.length, 1);
assert.equal(rubricBalance(rubric, scope).remaining, -10);
assert.equal(rubricBalance({ ...rubric, amount: 100 }, scope).status, 'matched');
assert.equal(rubricBalance({ ...rubric, amount: 110 }, scope).status, 'near');
assert.equal(rubricBalance({ ...rubric, amount: 200, previousAdjustment: 20 }, scope).remaining, 80);
assert.equal(rubricBalance({ ...rubric, amount: 200, previousAdjustment: -20 }, scope).remaining, 120);
const snapshot = structuredClone(scope[0]);
const reduced = { ...reductionSuggestion(scope[0], 10, rubric), company: 'Empresa A' };
assert.deepEqual(scope[0], snapshot, 'Sugerir redução não altera a origem');
assert.equal(invoiceTotal(reduced), 90);
assert.equal(reduced.items[0].quantity, 10, 'Preserva a quantidade entregue');
assert.equal(reduced.items[0].billedQuantity, 9);
assert.equal(reduced.rubric.deferred[0].quantity, 1);
assert.equal(validateInvoice(reduced), '');
const zero = reductionSuggestion(scope[0], 500, rubric);
assert.equal(invoiceTotal(zero), 0);
assert.equal(validateInvoice({ ...zero, company: 'Empresa A' }), '');
const edited = withDeferredItems({ ...reduced, items: [{ ...reduced.items[0], billedQuantity: 8 }] });
assert.equal(edited.rubric.deferred[0].quantity, 2, 'Recalcula a reserva pela edição final');
const updated = rubricMonthInvoices(orders, operations, points, prices, [reduced], '2026-11');
assert.equal(rubricBalance(rubric, rubricScopeInvoices(updated, rubric, orders, points)).remaining, 0);
const group = locationTotals([reduced], orders, points)[0];
const local = createLocationBillingInvoice(group, orders, prices, '2026-11-01', '2026-11-30', [], '2026-11-30');
assert.equal(invoiceTotal(local), 90, 'Consolidar preserva a redução já salva');
const consolidated = rubricMonthInvoices(orders, operations, points, prices, [reduced, local], '2026-11');
assert.equal(rubricScopeInvoices(consolidated, rubric, orders, points).length, 1, 'Consolidado substitui a origem');
assert.equal(rubricBalance(rubric, rubricScopeInvoices(consolidated, rubric, orders, points)).remaining, 0);
const catalog = ['Hortifrutigranjeiro', 'Proteínas', 'Dietas e Fórmulas', 'Estocáveis'].map((category, i) => ({ key: String(i), operationId: 'm', product: `Produto ${i}`, category, unit: 'KG', salePrice: 10 }));
const suggestions = complementSuggestion(catalog, rubric, 40);
assert.equal(suggestions.length, 4, 'Distribui entre as quatro categorias');
assert.equal(suggestions.reduce((sum, item) => sum + item.quantity * item.price, 0), 40);
assert.equal(complementSuggestion(catalog.map(row => ({ ...row, salePrice: null })), rubric, 40).length, 0);
const supplement = { ...createRubricInvoice(rubric, operations[1], points[0], suggestions, 'complement'), company: 'Empresa A' };
assert.equal(validateInvoice(supplement), '');
assert(billingInvoiceCategoryMatches(supplement, ['Proteínas']));
const withSupplement = rubricMonthInvoices(orders, operations, points, prices, [reduced, supplement], '2026-11');
assert.equal(rubricScopeInvoices(withSupplement, rubric, orders, points).length, 2);
const combined = createLocationBillingInvoice(locationTotals([reduced, supplement], orders, points)[0], orders, prices, '2026-11-01', '2026-11-30', [], '2026-11-30');
assert.equal(combined.items.length, 5, 'Complemento mult categoria não desaparece ao consolidar');
assert.equal(combined.location.categories.length, 4);
const next = { ...rubric, key: rubricKey('m', 'p1', '2026-12'), month: '2026-12' };
const carry = { ...createRubricInvoice(next, operations[1], points[0], reduced.rubric.deferred, 'carry', reduced.id), company: 'Empresa A' };
assert.equal(invoiceTotal(carry), 10);
assert.equal(createRubricInvoice(next, operations[1], points[0], reduced.rubric.deferred, 'carry', reduced.id).id, carry.id, 'Identificador impede duplicação de aproveitamento');
assert.equal(rubricMonthInvoices(orders, operations, points, prices, [reduced, carry], '2026-12').length, 1);
assert.equal(rubricScopeInvoices([carry], { ...next, pointId: 'p2' }, orders, points).length, 0, 'Não transfere entre locais de Maceió');
assert.equal(rubricMonthInvoices(orders, operations, points, prices, [reduced, carry], '2026-11').some(row => row.id === carry.id), false);
const discrete = complementSuggestion([{ ...catalog[0], unit: 'UN', salePrice: 3 }], rubric, 10);
assert.equal(discrete[0].quantity, 3);
console.log('OK: rubricas mensais, ajustes anteriores, locais individuais, reduções, reservas, complementos distribuídos, consolidados e aproveitamento sem duplicação.');
