import assert from 'node:assert/strict';
import * as XLSX from 'xlsx';
import { unzipSync } from 'fflate';
import { buildPeriodBillingArchive, buildOperationBillingSummary, buildOperationBillingWorkbook, selectOperationBillingOrders } from '../src/lib/operationBillingExcel.ts';

const operation = { id: 'maceio', name: 'Operação Maceió / teste' };
const makeOrder = (id, quantity, overrides = {}) => ({ id, operationId: operation.id, category: 'Hortifrutigranjeiro', deliveryDate: '2026-10-28', importedAt: '2026-10-27T22:23:00Z', deliveries: [{ items: [{ product: 'Arroz', unit: 'KG', quantity }] }], ...overrides });
const a = makeOrder('first', 3);
const b = makeOrder('second', 7, { generalNotes: 'Segunda entrega' });
const prices = { 'ARROZ|KG': { costPrice: 2, salePrice: 5 } };
const orders = [b, makeOrder('november', 999, { deliveryDate: '2026-11-01' }), a, makeOrder('other-op', 999, { operationId: 'other' }), makeOrder('other-category', 999, { category: 'Limpeza' })];
const snapshot = structuredClone(orders);
const archive = await buildPeriodBillingArchive(orders, operation, '2026-10-01', '2026-10-31', 'Hortifrutigranjeiro', prices);
const entries = unzipSync(archive.bytes);
assert.equal(archive.count, 2);
assert.equal(Object.keys(entries).length, 2, 'Um arquivo XLSX por romaneio, não uma aba por romaneio');
assert.ok(archive.filename.endsWith('.zip'));
const quantities = [];
for (const [name, bytes] of Object.entries(entries)) {
  assert.ok(name.endsWith('.xlsx'));
  assert.ok(name.includes('2026-10-28'));
  assert.ok(name.includes('27102026-1923'));
  assert.ok(!name.includes('/'), 'Nome do arquivo seguro para extração');
  const workbook = XLSX.read(bytes, { type: 'array', cellFormula: true, cellNF: true });
  assert.deepEqual(workbook.SheetNames, ['Faturamento']);
  const sheet = workbook.Sheets.Faturamento;
  const rows = XLSX.utils.sheet_to_json(sheet, { header: 1 });
  assert.equal(rows[1][1], operation.name);
  assert.equal(rows[1][3], a.category);
  assert.equal(rows[3][1], 1, 'Arquivo considera somente um pedido');
  const headerIndex = rows.findIndex(row => row[0] === 'Produto entregue');
  const product = rows[headerIndex + 1];
  quantities.push(product[2]);
  assert.deepEqual(product.slice(0, 2), ['Arroz', 'KG']);
  assert.equal(product[3], 2);
  assert.equal(product[4], 5);
  assert.equal(product[5], product[2] * 5);
  assert.equal(sheet[`F${headerIndex + 2}`].f, `C${headerIndex + 2}*E${headerIndex + 2}`);
  assert.equal(rows.at(-1)[5], product[2] * 5);
  assert.ok(sheet[`F${rows.length}`].f.startsWith('SUM('));
}
assert.deepEqual(quantities.sort((x, y) => x - y), [3, 7], 'Não mistura quantidades dos romaneios no mesmo período e controle');
assert.equal(new Set(Object.keys(entries)).size, 2, 'Mesmo controle/data não sobrescreve arquivos');
assert.deepEqual(orders, snapshot, 'Exportação não altera os pedidos');
const all = await buildPeriodBillingArchive(orders, operation, '2026-10-01', '2026-10-31', 'Todas', prices);
assert.equal(all.count, 3, 'Todas as categorias inclui os romaneios de categorias diferentes');
assert.equal(selectOperationBillingOrders([makeOrder('monthly', 11, { deliveryDate: '2026-10' })], operation.id, '2026-10-15', '2026-10-29', 'Todas').length, 1);
await assert.rejects(buildPeriodBillingArchive(orders, operation, '2026-11-10', '2026-10-01', 'Todas', prices));
await assert.rejects(buildPeriodBillingArchive(orders, operation, '2027-01-01', '2027-01-31', 'Todas', prices));
const empty = await buildPeriodBillingArchive([makeOrder('empty', 0, { deliveries: [] })], operation, '', '', 'Todas', prices);
assert.equal(Object.keys(unzipSync(empty.bytes)).length, 1, 'Inclui romaneio sem itens, com cabeçalho e total zero');
const merged = buildOperationBillingSummary([a, b]);
assert.equal(merged.rows[0].total, 10);
assert.equal(merged.orderCount, 2);
const mergedBook = buildOperationBillingWorkbook(merged, operation.name, 'Todas', 'Período completo', prices);
assert.equal(mergedBook.Sheets.Faturamento.C7.v, 10, 'Exportação consolidada continua somando os pedidos');
assert.equal(mergedBook.Sheets.Faturamento.F8.v, 50);
console.log('OK: ZIP com XLSX por romaneio, filtros, fórmulas, preços, nomes únicos, datas mensais e exportação consolidada.');
