import assert from 'node:assert/strict';
import { billingProductName, billingOperationPriceKey, billingPriceCatalog, billingPricesFromEntries, billingUnitPrice } from '../src/lib/igeveBilling.ts';
const op = { id: 'guaianases', name: 'Operação Guaianases (SP)', city: 'Guaianases' };
const key = (product, unit, operation = op.id, category = 'Estocáveis') => billingOperationPriceKey(operation, category, product, unit);
const oldKey = (product, unit) => 'gom_igeve_price_' + encodeURIComponent(JSON.stringify([op.id, 'ESTOCAVEIS', product, unit]));
const source = { filename: 'nota.pdf', hash: 'abc', invoice: '21', importedAt: '2026-11-09T20:00:00Z' };
const entry = (product, unit, price) => ({ key: oldKey(product, unit), operationId: op.id, category: 'Estocáveis', product, unit, salePrice: price, source });
assert.equal(billingProductName('IG. AÇÚCAR IG. CRISTAL 1KG'), 'AÇÚCAR CRISTAL 1KG');
assert.equal(billingProductName('FIG. INTEGRAL'), 'FIG. INTEGRAL');
assert.equal(key('IG. ACUCAR CRISTAL 1KG', 'KG'), key('Açúcar Cristal', '1 KG'));
assert.equal(key('ig. CACAU EM PO 200G', 'UN'), key('CACAU EM PÓ', '200G'));
assert.equal(key('IG. AZEITE 500ML', 'UN'), key('AZEITE', '500 ML'));
assert.notEqual(key('CACAU EM PO 200G', 'UN'), key('CACAU EM PO', '500G'));
assert.notEqual(key('CACAU EM PO 200G', 'KG'), key('CACAU EM PO', '200G'));
assert.notEqual(key('ARROZ', 'KG'), key('ARROZ', 'UN'));
assert.notEqual(key('ARROZ', 'KG'), key('ARROZ', 'KG', 'rio'));
assert.notEqual(key('ARROZ', 'KG'), key('ARROZ', 'KG', op.id, 'Proteínas'));
const orders = [{ id: 'order', operationId: op.id, category: 'Estocáveis', deliveries: [{ items: [{ product: 'Açúcar Cristal', unit: '1KG', quantity: 2 }, { product: 'CACAU EM PÓ', unit: '200G', quantity: 3 }] }] }];
const saved = [entry('IG. ACUCAR CRISTAL 1KG', 'KG', 6.2), entry('IG. CACAU EM PO 200G', 'UN', 58.8)];
const catalog = billingPriceCatalog(orders, [op], [], saved);
assert.equal(catalog.length, 2, 'Preço importado ocupa a linha pendente existente');
assert.deepEqual(catalog.map(row=>row.salePrice).sort((a,b)=>a-b), [6.2,58.8]);
assert.ok(catalog.every(row=>!row.product.includes('IG.')));
assert.ok(catalog.every(row=>row.source.filename==='nota.pdf'));
assert.equal(billingUnitPrice(billingPricesFromEntries(saved), op.id, 'Estocáveis', 'Açúcar Cristal', '1KG'), 6.2);
assert.equal(billingUnitPrice(billingPricesFromEntries(saved), op.id, 'Estocáveis', 'CACAU EM PÓ', '200G'), 58.8);
const pending = {...entry('AÇÚCAR CRISTAL', '1KG', null), source: undefined};
assert.equal(billingPriceCatalog(orders,[op],[],[...saved,pending]).find(row=>row.key===key('Açúcar Cristal','1KG')).salePrice,6.2);
const edited = {...catalog.find(row=>row.key===key('Açúcar Cristal','1KG')), salePrice:0, identityVersion:1};
assert.equal(billingUnitPrice(billingPricesFromEntries([edited,...saved]), op.id, 'Estocáveis', 'IG. ACUCAR CRISTAL 1KG','KG'),0,'Edição na chave atual prevalece sobre cópias antigas');
assert.equal(billingUnitPrice(billingPricesFromEntries([...saved,edited]), op.id, 'Estocáveis', 'Açúcar Cristal','1KG'),0);
const simplePending = entry('AVEIA', 'UN', null);
const simplePrice = entry('IG. AVEIA', 'UN', 3);
assert.equal(billingUnitPrice(billingPricesFromEntries([simplePending,simplePrice]),op.id,'Estocáveis','AVEIA','UN'),3);
assert.equal(billingUnitPrice(billingPricesFromEntries([simplePrice,simplePending]),op.id,'Estocáveis','AVEIA','UN'),3);
const cleared = {...edited, salePrice:null};
assert.equal(billingPricesFromEntries([cleared,...saved])[cleared.key],undefined,'Limpar preço não recupera valor antigo oculto');
assert.equal(billingPriceCatalog([], [op], [], saved).length,2,'Produtos importados sem romaneio continuam disponíveis');
console.log('OK: remoção de IG., embalagens equivalentes, itens pendentes substituídos, legado, origem, zero e isolamento por operação/categoria/unidade.');
